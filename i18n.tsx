const DICTS: Record<Lang, Dict> = { en, de, es, fr, ru };

export type ControlMode = "auto" | "keyboard" | "touch";

const LANG_KEY = "schoollife.lang";
const CTRL_KEY = "schoollife.controls";

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  controls: ControlMode;
  setControls: (c: ControlMode) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [controls, setControlsState] = useState<ControlMode>("auto");

  useEffect(() => {
    const l = localStorage.getItem(LANG_KEY) as Lang | null;
    if (l && DICTS[l]) setLangState(l);
    const c = localStorage.getItem(CTRL_KEY) as ControlMode | null;
    if (c === "auto" || c === "keyboard" || c === "touch") setControlsState(c);
  }, []);

  const value = useMemo<I18nValue>(() => ({
    lang,
    controls,
    setLang: (l) => { setLangState(l); localStorage.setItem(LANG_KEY, l); },
    setControls: (c) => { setControlsState(c); localStorage.setItem(CTRL_KEY, c); },
    t: (key) => DICTS[lang][key] ?? en[key] ?? key,
  }), [lang, controls]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    return {
      lang: "en", setLang: () => {}, controls: "auto", setControls: () => {},
      t: (k) => en[k] ?? k,
    };
  }
  return ctx;
}
